/** Asteroid shoal: shards over 4 s, two boulders, optionally a monolith in the middle. */
const shoal = (t: number, seed: number, shards = 5, monolith = false): WaveBlock[] => [
  field(t, 'r_shard', shards, 4, seed),
  field(t + 1, 'r_boulder', 2, 3, seed + 7),
  monolith ? one(t + 2, 'r_monolith', 0.5) : [],
];
/** Graviton mine field drifting in over `span` seconds. */
const mines = (t: number, seed: number, n = 4, span = 4): WaveBlock => field(t, 'r_mine', n, span, seed);
/** Comet pack: two hunting columns from the upper corners. */
const comets = (t: number, n = 3, interval = 0.4): WaveBlock[] => [
  col(t, 'r_comet', 0.15, n, interval), col(t + 0.3, 'r_comet', 0.85, n, interval),
];

