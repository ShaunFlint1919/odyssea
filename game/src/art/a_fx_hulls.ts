// =====================================================================================
//  A-FX HULL MAPS — hand-authored LEFT halves of the six player hulls (16 x 32) and the
//  six sidekick drones (8 x 16). Rows are RIGHT-ALIGNED: each string ends on the column
//  next to the centre line and is padded with '.' on the left (see padHalf). The halves are
//  mirrored with mirrorH(), then lit / banked by src/art/player.ts. Nose UP, nozzles at the
//  bottom, 1px transparent margin everywhere (the dark outline is added afterwards).
//
//  Legend:  1-5 hull ramp (dark -> light)      6-9 accent ramp (dark -> light)
//           g G h H metal ramp                 c C q canopy (dark, mid, light), w glint
//           e E y engine glow (dark -> hot)    n N neon light (dark, bright)
//           k dark panel line / recess         . transparent
// =====================================================================================

export interface HullScheme {
  hull: [string, string, string, string, string];
  accent: [string, string, string, string];
  canopy: [string, string, string];
  neon: [string, string];
}

export interface HullArt {
  half: string[];               // right-aligned rows (<= 16 chars), 32 rows
  scheme: HullScheme;
  fuselage: number;             // rigid fuselage half-width in px (banking squashes what is outside)
  engines: [number, number][];  // nozzle exit points, px from the sprite centre (x, y)
  nose: [number, number];       // main gun muzzle, px from the sprite centre
}

/** Right-align rows to a fixed half width. */
export function padHalf(rows: string[], w: number): string[] {
  return rows.map((r) => (r.length > w ? r.slice(r.length - w) : r.padStart(w, '.')));
}

