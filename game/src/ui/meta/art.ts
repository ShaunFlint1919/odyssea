/** Soft white radial glow (smooth falloff, for ADD blending). */
function softGlow(size: number): HTMLCanvasElement {
  const { canvas, ctx } = makeCanvas(size, size);
  const img = ctx.createImageData(size, size);
  const c = (size - 1) / 2;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const d = Math.hypot(x - c, y - c) / (size / 2);
      const a = Math.max(0, 1 - d) ** 2;
      const i = (y * size + x) * 4;
      img.data[i] = 255; img.data[i + 1] = 255; img.data[i + 2] = 255; img.data[i + 3] = Math.round(a * 255);
    }
  }
  ctx.putImageData(img, 0, 0);
  return canvas;
}

/** Pixel ring of radius r (white). */
function ringTexture(r: number, thick: number): HTMLCanvasElement {
  const size = r * 2 + 4;
  const { canvas, ctx } = makeCanvas(size, size);
  const img = ctx.createImageData(size, size);
  const c = (size - 1) / 2;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const d = Math.abs(Math.hypot(x - c, y - c) - r);
      const a = d < thick * 0.5 ? 1 : d < thick * 0.5 + 1 ? 0.35 : 0;
      if (!a) continue;
      const i = (y * size + x) * 4;
      img.data[i] = 255; img.data[i + 1] = 255; img.data[i + 2] = 255; img.data[i + 3] = Math.round(a * 255);
    }
  }
  ctx.putImageData(img, 0, 0);
  return canvas;
}

/** Selection reticle: four corner brackets around a square (white, tinted). */
function reticleTexture(s: number): HTMLCanvasElement {
  const { canvas, ctx } = makeCanvas(s, s);
  ctx.fillStyle = '#ffffff';
  const l = 6;
  const corner = (x: number, y: number, dx: number, dy: number) => {
    ctx.fillRect(dx > 0 ? x : x - l + 1, y, l, 1);
    ctx.fillRect(x, dy > 0 ? y : y - l + 1, 1, l);
    ctx.fillRect(dx > 0 ? x : x - l + 1, y + (dy > 0 ? 1 : -1), l, 1);
    ctx.fillRect(x + (dx > 0 ? 1 : -1), dy > 0 ? y : y - l + 1, 1, l);
  };
  corner(0, 0, 1, 1);
  corner(s - 1, 0, -1, 1);
  corner(0, s - 1, 1, -1);
  corner(s - 1, s - 1, -1, -1);
  return canvas;
}

/** Dark soft ellipse (ship hover shadow). */
function shadowEllipse(w: number, h: number): HTMLCanvasElement {
  const { canvas, ctx } = makeCanvas(w, h);
  const img = ctx.createImageData(w, h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const dx = (x + 0.5 - w / 2) / (w / 2);
      const dy = (y + 0.5 - h / 2) / (h / 2);
      const d = Math.sqrt(dx * dx + dy * dy);
      if (d >= 1) continue;
      const a = (1 - d) ** 1.2 * 0.8;
      const aa = bayer(x, y) < a * 1.6 ? a : a * 0.55;
      const i = (y * w + x) * 4;
      img.data[i] = 0; img.data[i + 1] = 0; img.data[i + 2] = 6;
      img.data[i + 3] = Math.round(aa * 255);
    }
  }
  ctx.putImageData(img, 0, 0);
  return canvas;
}

