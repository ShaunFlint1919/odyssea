let generated = false;

/** Creates every meta texture once (cheap no-op afterwards). */
export function ensureMetaArt(scene: Phaser.Scene): void {
  if (generated && scene.textures.exists(META.reticle)) return;
  generated = true;
  for (const [key, map] of Object.entries(ICONS)) {
    if (!scene.textures.exists(key)) addTexture(scene, key, mapToCanvas(map, C));
  }
  if (!scene.textures.exists(META.arc)) addTexture(scene, META.arc, shieldArc(54, 54));
  if (!scene.textures.exists(META.glow)) addTexture(scene, META.glow, softGlow(32));
  if (!scene.textures.exists(META.ring)) addTexture(scene, META.ring, ringTexture(32, 2));
  if (!scene.textures.exists(META.shadow)) addTexture(scene, META.shadow, shadowEllipse(64, 16));
  if (!scene.textures.exists(META.flame)) addTexture(scene, META.flame, flameFallback());
  if (!scene.textures.exists(META.reticle)) addTexture(scene, META.reticle, reticleTexture(28));
}

/**
 * Shield arc texture of radius r (cached). The arc centre lies (r + 6) px below the texture
 * top: use setOrigin(0.5, shieldArcOriginY(r)) and place the image at the ship centre.
 */
export function shieldArcKey(scene: Phaser.Scene, r: number): string {
  r = Math.max(8, Math.round(r));
  const key = `${META.arc}_${r}`;
  if (!scene.textures.exists(key)) addTexture(scene, key, shieldArc(r, r));
  return key;
}
export const shieldArcOriginY = (r: number): number => {
  r = Math.max(8, Math.round(r));
  const h = Math.ceil(r - r * Math.cos((68 * Math.PI) / 180)) + 12;
  return (r + 6) / h;
};

/** Icon key if present, else the fallback key. */
export const iconOr = (scene: Phaser.Scene, key: string, fallback: string): string => (scene.textures.exists(key) ? key : fallback);

