/**
 * Shield arc (white, tint at runtime, ADD blend): an arc of radius r above a centre that lies
 * `below` px under the canvas top, spanning +-68 deg around "up". Bright 1px core, inner glow,
 * dithered outer haze and a row of brighter emitter nodes.
 */
function shieldArc(r: number, below: number): HTMLCanvasElement {
  const w = r * 2 + 12;
  const h = Math.ceil(r - r * Math.cos((68 * Math.PI) / 180)) + 12;
  const cx = w / 2;
  const cy = below + 6;
  const { canvas, ctx } = makeCanvas(w, h);
  const img = ctx.createImageData(w, h);
  const span = (68 * Math.PI) / 180;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const dx = x + 0.5 - cx;
      const dy = y + 0.5 - cy;
      const d = Math.hypot(dx, dy);
      const dev = Math.abs(Math.atan2(dy, dx) + Math.PI / 2);
      if (dev > span) continue;
      const edge = Math.min(1, (span - dev) / 0.35);
      const off = Math.abs(d - r);
      let a = 0;
      if (off < 0.75) a = 1;
      else if (off < 1.75) a = 0.62;
      else if (off < 3.2) a = 0.26;
      else if (off < 5) a = bayer(x, y) < 0.3 ? 0.16 : 0;
      // emitter nodes every ~11 degrees on the core line
      const node = Math.abs(((dev * 180) / Math.PI) % 11 - 5.5) < 0.9 && off < 2.2;
      if (node) a = Math.min(1, a + 0.35);
      a *= edge;
      if (a <= 0.01) continue;
      const i = (y * w + x) * 4;
      img.data[i] = 255; img.data[i + 1] = 255; img.data[i + 2] = 255; img.data[i + 3] = Math.round(a * 255);
    }
  }
  ctx.putImageData(img, 0, 0);
  return canvas;
}

// ------------------------------------------------------------------------- sized backgrounds

const hex = (c: string): [number, number, number] => { const [r, g, b] = parseColor(c); return [r, g, b]; };
const lerp3 = (a: [number, number, number], b: [number, number, number], t: number): [number, number, number] =>
  [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];

/**
 * Ship-bay screen backdrop (w x h): ribbed hangar wall with marker lights above a perspective
 * floor grid fading into the distance. Cached per size.
 */
export function bayBackdrop(scene: Phaser.Scene, w: number, h: number): string {
  w = Math.max(16, Math.round(w)); h = Math.max(16, Math.round(h));
  const key = `meta_bay_${w}x${h}`;
  if (scene.textures.exists(key)) return key;
  const { canvas, ctx } = makeCanvas(w, h);
  const img = ctx.createImageData(w, h);
  const d = img.data;
  const hy = Math.round(h * 0.6);
  const wallTop = hex('#0a0916'), wallLow = hex('#1c1934');
  const floorNear = hex('#07060e'), floorFar = hex('#17142c');
  const grid = hex('#2ee6c8');
  const rib = 26;
  const vpY = hy - h * 0.9;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      let c: [number, number, number];
      if (y < hy) {
        const t = y / hy;
        const dither = bayer(x, y) * 0.08;
        c = lerp3(wallTop, wallLow, Math.min(1, t * t + dither));
        const rx = (x + 7) % rib;
        if (rx === 0) c = lerp3(c, [4, 3, 10], 0.75);
        else if (rx === 1) c = lerp3(c, [58, 53, 88], 0.35);
        // horizontal panel seam + marker lights
        if (y === hy - 16) c = lerp3(c, [4, 3, 10], 0.6);
        if (y === hy - 12 && (x + 7) % rib === 13) c = [46, 230, 200];
        if (y === hy - 12 && (x + 7) % rib === 12) c = lerp3(c, [46, 230, 200], 0.35);
        if (y === hy - 12 && (x + 7) % rib === 14) c = lerp3(c, [46, 230, 200], 0.35);
        if (y === 6 && (x + 20) % (rib * 2) < 2) c = [208, 76, 255];
        if (y === hy - 1) c = lerp3(c, grid, 0.28);
      } else {
        const t = (y - hy) / Math.max(1, h - hy);
        c = lerp3(floorFar, floorNear, Math.min(1, t + bayer(x, y) * 0.06));
        // perspective grid: depth lines + radial lines from the vanishing point
        const z = 1 / (t + 0.06);
        const zPrev = 1 / (Math.max(0, (y - 1 - hy) / Math.max(1, h - hy)) + 0.06);
        const depthLine = Math.floor(z * 0.9) !== Math.floor(zPrev * 0.9);
        const k = (x + 0.5 - w / 2) / ((y - vpY) / (hy - vpY));
        const kPrev = (x - 0.5 - w / 2) / ((y - vpY) / (hy - vpY));
        const radial = Math.floor(k / 22) !== Math.floor(kPrev / 22);
        if (depthLine || radial) {
          const fade = 0.1 + 0.32 * Math.min(1, t * 1.6);
          c = lerp3(c, grid, fade);
        }
      }
      // vignette
      const vx = (x / (w - 1)) * 2 - 1, vy = (y / (h - 1)) * 2 - 1;
      const v = Math.max(0, Math.hypot(vx * 0.85, vy) - 0.55);
      c = lerp3(c, [2, 1, 6], Math.min(0.7, v * 0.9));
      const i = (y * w + x) * 4;
      d[i] = c[0]; d[i + 1] = c[1]; d[i + 2] = c[2]; d[i + 3] = 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  addTexture(scene, key, canvas);
  return key;
}

/**
 * Galaxy-map nebula (half resolution, scaled x2 when displayed): deep-space gradient with
 * magenta / teal / indigo fbm clouds and a few bright cores. Cached per size.
 */
export function nebulaBackdrop(scene: Phaser.Scene, w: number, h: number, seed = 7): string {
  const hw = Math.ceil(w / 2), hh = Math.ceil(h / 2);
  const key = `meta_nebula_${hw}x${hh}_${seed}`;
  if (scene.textures.exists(key)) return key;
  const { canvas, ctx } = makeCanvas(hw, hh);
  const img = ctx.createImageData(hw, hh);
  const base0 = hex('#06050d'), base1 = hex('#0c0a1c');
  const mag = hex('#6a1e8a'), teal = hex('#0d6a66'), ind = hex('#24206a');
  for (let y = 0; y < hh; y++) {
    for (let x = 0; x < hw; x++) {
      const nx = x / 48, ny = y / 48;
      const n1 = fbm(nx, ny, seed, 4);
      const n2 = fbm(nx * 1.3 + 7.1, ny * 1.3 - 3.7, seed + 31, 4);
      const n3 = fbm(nx * 0.7 - 2.2, ny * 0.7 + 5.1, seed + 77, 3);
      // two diagonal nebula lanes
      const lane1 = Math.exp(-(((x - y * 0.55 - hw * 0.1) / (hw * 0.45)) ** 2));
      const lane2 = Math.exp(-(((x + y * 0.4 - hw * 1.05) / (hw * 0.38)) ** 2));
      let c = lerp3(base0, base1, y / hh);
      const m = Math.max(0, n1 - 0.42) * 2.2 * lane1;
      const t = Math.max(0, n2 - 0.45) * 2.2 * lane2;
      const i3 = Math.max(0, n3 - 0.4) * 1.4;
      c = lerp3(c, ind, Math.min(0.6, i3));
      c = lerp3(c, mag, Math.min(0.75, m));
      c = lerp3(c, teal, Math.min(0.7, t));
      // dithering keeps it pixel-art (posterised bands)
      const q = 10;
      const b = (bayer(x, y) - 0.5) * q;
      const r = Math.round((c[0] + b) / q) * q, g = Math.round((c[1] + b) / q) * q, bb = Math.round((c[2] + b) / q) * q;
      // sparse static stars
      const hsh = hash2(x, y, seed);
      const star = hsh > 0.9965 ? (hsh > 0.9992 ? 255 : 150) : 0;
      const i = (y * hw + x) * 4;
      img.data[i] = Math.max(r, star); img.data[i + 1] = Math.max(g, star); img.data[i + 2] = Math.max(bb, star); img.data[i + 3] = 255;
    }
  }
  ctx.putImageData(img, 0, 0);
  addTexture(scene, key, canvas);
  return key;
}

/**
 * Smoothly resampled copy of a texture frame at `size` px (planet globes on the map, item
 * thumbnails). Returns the new key, or null when the source is missing.
 */
export function resampled(scene: Phaser.Scene, srcKey: string, size: number, frame?: string | number, smooth = true): string | null {
  if (!scene.textures.exists(srcKey)) return null;
  const key = `meta_rs_${srcKey}_${frame ?? 'b'}_${size}_${smooth ? 1 : 0}`;
  if (scene.textures.exists(key)) return key;
  const tex = scene.textures.get(srcKey);
  const fr = frame !== undefined && tex.has(String(frame)) ? tex.get(frame) : tex.get();
  const src = fr.source.image as CanvasImageSource;
  const { canvas, ctx } = makeCanvas(size, size);
  const sw = fr.cutWidth, sh = fr.cutHeight;
  const s = Math.min(size / sw, size / sh);
  const dw = Math.round(sw * s), dh = Math.round(sh * s);
  if (smooth && s < 1) {
    // two-step downscale for better quality
    const mid = makeCanvas(Math.max(dw, Math.round(sw / 2)), Math.max(dh, Math.round(sh / 2)));
    mid.ctx.imageSmoothingEnabled = true;
    mid.ctx.imageSmoothingQuality = 'high';
    mid.ctx.drawImage(src, fr.cutX, fr.cutY, sw, sh, 0, 0, mid.canvas.width, mid.canvas.height);
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(mid.canvas, 0, 0, mid.canvas.width, mid.canvas.height, Math.floor((size - dw) / 2), Math.floor((size - dh) / 2), dw, dh);
  } else {
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(src, fr.cutX, fr.cutY, sw, sh, Math.floor((size - dw) / 2), Math.floor((size - dh) / 2), dw, dh);
  }
  addTexture(scene, key, canvas);
  return key;
}

/**
 * 16x16 "chip" icon for a shop item: dark rounded plate with a coloured rim and the given
 * texture frame (projectile, sidekick, hull...) drawn centred inside, downsampled with a
 * majority filter when larger than the plate. Returns the key (or null without source art).
 */
export function chipIcon(scene: Phaser.Scene, id: string, srcKey: string | null, rim: number, opts: { frame?: string | number; fit?: number } = {}): string | null {
  const key = `meta_chip_${id}`;
  if (scene.textures.exists(key)) return key;
  const { canvas, ctx } = makeCanvas(16, 16);
  // plate
  ctx.fillStyle = '#0a0810';
  ctx.fillRect(1, 0, 14, 16); ctx.fillRect(0, 1, 16, 14);
  ctx.fillStyle = '#1c1a2a';
  ctx.fillRect(2, 1, 12, 14); ctx.fillRect(1, 2, 14, 12);
  const r = (rim >> 16) & 255, g = (rim >> 8) & 255, b = rim & 255;
  ctx.fillStyle = `rgba(${r},${g},${b},0.85)`;
  ctx.fillRect(2, 1, 12, 1); ctx.fillRect(1, 2, 1, 12);
  ctx.fillStyle = `rgba(${r},${g},${b},0.4)`;
  ctx.fillRect(2, 14, 12, 1); ctx.fillRect(14, 2, 1, 12);
  if (srcKey && scene.textures.exists(srcKey)) {
    const tex = scene.textures.get(srcKey);
    const fr = opts.frame !== undefined && tex.has(String(opts.frame)) ? tex.get(opts.frame) : tex.get();
    const src = fr.source.image as CanvasImageSource;
    const fitPx = opts.fit ?? 12;
    const sw = fr.cutWidth, sh = fr.cutHeight;
    if (sw <= fitPx && sh <= fitPx) {
      ctx.drawImage(src, fr.cutX, fr.cutY, sw, sh, Math.floor((16 - sw) / 2), Math.floor((16 - sh) / 2), sw, sh);
    } else {
      const scaled = majorityDownscale(src, fr.cutX, fr.cutY, sw, sh, fitPx);
      ctx.drawImage(scaled, Math.floor((16 - scaled.width) / 2), Math.floor((16 - scaled.height) / 2));
    }
  } else if (srcKey) {
    return null;
  }
  addTexture(scene, key, canvas);
  return key;
}

/** Downscale pixel art by an integer-ish factor keeping crisp pixels (dominant opaque colour per block). */
function majorityDownscale(src: CanvasImageSource, sx: number, sy: number, sw: number, sh: number, fitPx: number): HTMLCanvasElement {
  const f = Math.max(1, Math.ceil(Math.max(sw, sh) / fitPx));
  const ow = Math.ceil(sw / f), oh = Math.ceil(sh / f);
  const a = makeCanvas(sw, sh);
  a.ctx.drawImage(src, sx, sy, sw, sh, 0, 0, sw, sh);
  const sd = a.ctx.getImageData(0, 0, sw, sh).data;
  const out = makeCanvas(ow, oh);
  const od = out.ctx.createImageData(ow, oh);
  for (let y = 0; y < oh; y++) {
    for (let x = 0; x < ow; x++) {
      let n = 0, r = 0, g = 0, b = 0, cnt = 0;
      let brightest = -1, br = 0, bg = 0, bb = 0;
      for (let yy = 0; yy < f; yy++) {
        for (let xx = 0; xx < f; xx++) {
          const px = x * f + xx, py = y * f + yy;
          if (px >= sw || py >= sh) continue;
          cnt++;
          const i = (py * sw + px) * 4;
          if (sd[i + 3] < 128) continue;
          n++; r += sd[i]; g += sd[i + 1]; b += sd[i + 2];
          const lum = sd[i] * 0.3 + sd[i + 1] * 0.59 + sd[i + 2] * 0.11;
          if (lum > brightest) { brightest = lum; br = sd[i]; bg = sd[i + 1]; bb = sd[i + 2]; }
        }
      }
      if (n * 2 < cnt) continue;
      const o = (y * ow + x) * 4;
      // average, nudged towards the brightest pixel so highlights survive
      od.data[o] = (r / n) * 0.6 + br * 0.4;
      od.data[o + 1] = (g / n) * 0.6 + bg * 0.4;
      od.data[o + 2] = (b / n) * 0.6 + bb * 0.4;
      od.data[o + 3] = 255;
    }
  }
  out.ctx.putImageData(od, 0, 0);
  return out.canvas;
}

