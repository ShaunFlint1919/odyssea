/** 16x16 icon of frame `frame` of a sprite sheet (nearest copy, or majority downscale when larger). */
export function frameIcon(scene: Phaser.Scene, srcKey: string, frame: string | number = 0): string | null {
  if (!scene.textures.exists(srcKey)) return null;
  const key = `meta_fi_${srcKey}_${frame}`;
  if (scene.textures.exists(key)) return key;
  const tex = scene.textures.get(srcKey);
  const fr = tex.has(String(frame)) ? tex.get(frame) : tex.get();
  const src = fr.source.image as CanvasImageSource;
  const { canvas, ctx } = makeCanvas(16, 16);
  if (fr.cutWidth <= 16 && fr.cutHeight <= 16) {
    ctx.drawImage(src, fr.cutX, fr.cutY, fr.cutWidth, fr.cutHeight, Math.floor((16 - fr.cutWidth) / 2), Math.floor((16 - fr.cutHeight) / 2), fr.cutWidth, fr.cutHeight);
  } else {
    const small = majorityDownscale(src, fr.cutX, fr.cutY, fr.cutWidth, fr.cutHeight, 16);
    ctx.drawImage(small, Math.floor((16 - small.width) / 2), Math.floor((16 - small.height) / 2));
  }
  addTexture(scene, key, canvas);
  return key;
}

function plate(ctx: CanvasRenderingContext2D, rim: number): void {
  ctx.fillStyle = '#0a0810';
  ctx.fillRect(1, 0, 14, 16); ctx.fillRect(0, 1, 16, 14);
  ctx.fillStyle = '#1c1a2a';
  ctx.fillRect(2, 1, 12, 14); ctx.fillRect(1, 2, 14, 12);
  const r = (rim >> 16) & 255, g = (rim >> 8) & 255, b = rim & 255;
  ctx.fillStyle = `rgba(${r},${g},${b},0.85)`;
  ctx.fillRect(2, 1, 12, 1); ctx.fillRect(1, 2, 1, 12);
  ctx.fillStyle = `rgba(${r},${g},${b},0.4)`;
  ctx.fillRect(2, 14, 12, 1); ctx.fillRect(14, 2, 1, 12);
}

const rgb = (c: number, a = 1): string => `rgba(${(c >> 16) & 255},${(c >> 8) & 255},${c & 255},${a})`;

/** Shield item chip: plate + bubble ring in the shield colour; `tier` (1..) adds inner rings. */
export function shieldChip(scene: Phaser.Scene, id: string, color: number, tier: number): string {
  const key = `meta_sc_${id}`;
  if (scene.textures.exists(key)) return key;
  const { canvas, ctx } = makeCanvas(16, 16);
  plate(ctx, color);
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x + 0.5 - 8, y + 0.5 - 8.5);
      if (Math.abs(d - 5) < 0.6) { ctx.fillStyle = rgb(color); ctx.fillRect(x, y, 1, 1); }
      else if (d < 4.4 && tier >= 3) { ctx.fillStyle = rgb(color, 0.25 + 0.05 * tier); ctx.fillRect(x, y, 1, 1); }
      else if (Math.abs(d - 3) < 0.5 && tier >= 2) { ctx.fillStyle = rgb(color, 0.55); ctx.fillRect(x, y, 1, 1); }
    }
  }
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(6, 5, 2, 1); ctx.fillRect(5, 6, 1, 1);
  addTexture(scene, key, canvas);
  return key;
}

/** Generator item chip: plate + energy cell bars (count = tier) under a bolt. */
export function generatorChip(scene: Phaser.Scene, id: string, tier: number): string {
  const key = `meta_gc_${id}`;
  if (scene.textures.exists(key)) return key;
  const { canvas, ctx } = makeCanvas(16, 16);
  plate(ctx, 0xffd060);
  const bolt = ['..yy', '.yy.', 'yyyy', '.yy.', 'yy..'];
  bolt.forEach((row, y) => [...row].forEach((ch, x) => { if (ch === 'y') { ctx.fillStyle = '#ffe060'; ctx.fillRect(6 + x, 2 + y, 1, 1); } }));
  const n = Math.max(1, Math.min(6, tier));
  for (let i = 0; i < 6; i++) {
    ctx.fillStyle = i < n ? (i >= 4 ? '#ff8040' : '#2ee6c8') : '#2a2638';
    ctx.fillRect(2 + i * 2, 9, 1, 4);
  }
  addTexture(scene, key, canvas);
  return key;
}

